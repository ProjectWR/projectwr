// Helper function to get fields by category
export const getFieldsByCategory = (config) => {
  const categories = {};
  Object.entries(config).forEach(([key, fieldConfig]) => {
    const category = fieldConfig.category || "other";
    if (!categories[category]) {
      categories[category] = {};
    }
    categories[category][key] = fieldConfig;
  });
  return categories;
};

